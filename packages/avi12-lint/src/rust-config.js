import { mergeFlatToml, parseFlatToml, renderEntries } from "./flat-toml.js";

/** The preset package a consumer installs. */
export const RUST_PRESET_DIRECTORY = "node_modules/rust-config-avi12";

/** The repo's own exemptions and additions, next to the workspace manifest. */
export const RUST_LOCAL_FILE = "avi12-rust.local.toml";

const BEGIN_MARKER = "# avi12-lint:begin rust-config (generated from rust-config-avi12; edit avi12-rust.local.toml)";
const END_MARKER = "# avi12-lint:end";
const MANAGED_BLOCK = /\n?# avi12-lint:begin rust-config[^\n]*\n[\s\S]*?# avi12-lint:end\n?/;
const FOREIGN_LINTS = /^\s*\[(?:workspace\.)?lints(?:[.\]])/m;
const MEMBER_TABLE = /^member\.(.+)\.(rust|clippy)$/;
const DENY_PREFIX = "deny.";
const GENERATED_BANNER =
  "# Generated by avi12-lint rust-config from rust-config-avi12 and avi12-rust.local.toml; do not edit";

function directoryOf(file) {
  const slash = file.lastIndexOf("/");
  return slash === -1 ? "." : file.slice(0, slash);
}

function isInside({ file, directory }) {
  return directory === "." || file.startsWith(`${directory}/`);
}

function joinPath({ directory, name }) {
  return directory === "." ? name : `${directory}/${name}`;
}

function packageName(text) {
  return /^\s*\[package\][^[]*?^\s*name\s*=\s*"([^"]+)"/ms.exec(text)?.[1];
}

/**
 * The Cargo roots of a repo, from its manifests (`{ path, text }`, repo-relative with `/`): every manifest with a
 * `[workspace]` table, plus each package that lies in no workspace. A root is `{ directory, manifest, isWorkspace,
 * crates }`, `crates` being `{ name, directory, manifest }` of every package under it. Pure.
 */
export function cargoRoots(manifests) {
  const workspaces = manifests
    .filter(({ text }) => /^\s*\[workspace\]/m.test(text))
    .map(({ path }) => directoryOf(path));
  const roots = manifests
    .filter(({ path, text }) => {
      const directory = directoryOf(path);
      const isInOther = workspaces.some(
        other =>
          other !== directory &&
          isInside({
            file: path,
            directory: other
          })
      );
      return workspaces.includes(directory) || (!isInOther && packageName(text));
    })
    .map(({ path }) => ({
      directory: directoryOf(path),
      manifest: path,
      isWorkspace: workspaces.includes(directoryOf(path))
    }));
  const owners = [...roots].sort((one, two) => one.directory.length - two.directory.length);
  return roots.map(root => ({
    ...root,
    crates: manifests.flatMap(({ path, text }) => {
      const owner = owners
        .filter(other =>
          isInside({
            file: path,
            directory: other.directory
          })
        )
        .pop();
      const name = packageName(text);
      const isOwned = owner?.directory === root.directory && name;
      return isOwned
        ? [
            {
              name,
              directory: directoryOf(path),
              manifest: path
            }
          ]
        : [];
    })
  }));
}

function renderLints({ lints, prefix }) {
  return ["rust", "clippy"].flatMap(table => [`[${prefix}.${table}]`, ...renderEntries(lints.get(table) ?? new Map())]);
}

function memberOverride({ local, name }) {
  const override = new Map();
  for (const [table, entries] of local) {
    const match = MEMBER_TABLE.exec(table);
    if (match?.[1] === name) {
      override.set(match[2], entries);
    }
  }

  return override.size > 0 ? override : undefined;
}

/** Puts `lines` between the markers of a manifest: replaces the block that is there, else appends it. Pure. */
export function withManagedBlock({ text, lines }) {
  const block = `${BEGIN_MARKER}\n${lines.join("\n")}\n${END_MARKER}\n`;
  const hasBlock = MANAGED_BLOCK.test(text);
  return hasBlock ? text.replace(MANAGED_BLOCK, () => `\n${block}`) : `${text.replace(/\s+$/, "")}\n\n${block}`;
}

function crateLines({ crate, lints, local, isWorkspace }) {
  const override = memberOverride({
    local,
    name: crate.name
  });
  if (isWorkspace && !override) {
    return ["[lints]", "workspace = true"];
  }

  return renderLints({
    lints: override
      ? mergeFlatToml({
          base: lints,
          local: override
        })
      : lints,
    prefix: "lints"
  });
}

function toolConfig({ preset, local, name }) {
  const isLint = name === "deny";
  const own = isLint
    ? new Map(
        [...local]
          .filter(([table]) => table.startsWith(DENY_PREFIX))
          .map(([table, entries]) => [table.slice(DENY_PREFIX.length), entries])
      )
    : new Map([["", local.get(name === "clippy" ? "clippy-config" : name) ?? new Map()]]);
  const merged = mergeFlatToml({
    base: parseFlatToml(preset[name]),
    local: own
  });
  const lines = [GENERATED_BANNER];
  for (const [table, entries] of merged) {
    if (entries.size > 0) {
      lines.push(...(table ? ["", `[${table}]`] : []), ...renderEntries(entries));
    }
  }

  return `${lines.join("\n")}\n`;
}

function manifestBlocks({ root, lints, local }) {
  function linesOf(crate) {
    return crateLines({
      crate,
      lints,
      local,
      isWorkspace: root.isWorkspace
    });
  }
  const workspaceLines = root.isWorkspace
    ? renderLints({
        lints,
        prefix: "workspace.lints"
      })
    : [];
  const rootCrate = root.crates.find(crate => crate.manifest === root.manifest);
  const rootBlock = root.isWorkspace
    ? [
        {
          path: root.manifest,
          lines: rootCrate ? [...workspaceLines, "", ...linesOf(rootCrate)] : workspaceLines
        }
      ]
    : [];
  const others = root.crates
    .filter(crate => !root.isWorkspace || crate.manifest !== root.manifest)
    .map(crate => ({
      path: crate.manifest,
      lines: linesOf(crate)
    }));
  return [...rootBlock, ...others];
}

/**
 * Works out every file `avi12-lint rust-config` writes: per root the `clippy.toml`, `rustfmt.toml` and `deny.toml`
 * (the preset merged with the root's `avi12-rust.local.toml`) and the manifests with their managed lint blocks.
 * `preset` is `{ lints, clippy, rustfmt, deny }` as text, `manifests` as for `cargoRoots`, `locals` maps a root
 * directory to its local file's text. Returns `{ files: Map<path, text>, problems }`; a problem is a manifest that
 * keeps its own `[lints]` tables outside the managed block. Pure.
 */
export function planRustConfig({ preset, manifests, locals }) {
  const files = new Map();
  const problems = [];
  for (const root of cargoRoots(manifests)) {
    const local = parseFlatToml(locals.get(root.directory) ?? "");
    const lints = mergeFlatToml({
      base: parseFlatToml(preset.lints),
      local
    });
    for (const name of ["clippy", "rustfmt", "deny"]) {
      files.set(
        joinPath({
          directory: root.directory,
          name: `${name}.toml`
        }),
        toolConfig({
          preset,
          local,
          name
        })
      );
    }

    const rootBlocks = manifestBlocks({
      root,
      lints,
      local
    });
    for (const { path, lines } of rootBlocks) {
      const { text } = manifests.find(manifest => manifest.path === path);
      const isForeign = FOREIGN_LINTS.test(text.replace(MANAGED_BLOCK, ""));
      if (isForeign) {
        problems.push(`${path}: has [lints] tables of its own; move them to ${RUST_LOCAL_FILE} and delete them`);
        continue;
      }

      files.set(
        path,
        withManagedBlock({
          text,
          lines
        })
      );
    }
  }

  return {
    files,
    problems
  };
}

/** The paths whose current text (`existing`, a Map; a missing file is undefined) differs from what is wanted. */
export function staleRustFiles({ files, existing }) {
  return [...files].filter(([path, text]) => existing.get(path) !== text).map(([path]) => path);
}
