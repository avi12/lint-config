class CyclomaticComplexMethod {
  fun check(value: Int): Int {
    if (value == 10) {
      return 0
    }
    if (value == 11) {
      return 1
    }
    if (value == 12) {
      return 2
    }
    if (value == 13) {
      return 3
    }
    if (value == 14) {
      return 4
    }
    if (value == 15) {
      return 5
    }
    if (value == 16) {
      return 6
    }
    if (value == 17) {
      return 7
    }
    if (value == 18) {
      return 8
    }
    if (value == 19) {
      return 9
    }
    if (value == 20) {
      return 10
    }
    if (value == 21) {
      return 11
    }
    if (value == 22) {
      return 12
    }
    if (value == 23) {
      return 13
    }
    if (value == 24) {
      return 14
    }
    if (value == 25) {
      return 15
    }
    return 0
  }
}
